def draw(spec):
    data = dict(spec)
    kind = data.pop("type", "grid")
    if kind == "chain":
        return chain(**data)
    if kind == "graph":
        return graph(**data)
    return grid(**data)

def make(spec):
    def paint():
        if "frames" in spec:
            return [draw(p) for p in spec["frames"]], [2000] * len(spec["frames"])
        return draw(spec)
    return paint

for name, spec in PANELS.items():
    globals()["draw_" + name.replace("-", "_")] = figure(name, *SIZE)(make(spec))

def side(h, k, p=0, s=1):
    return (h + 2*p-k)//s + 1
assert side(5,3) == 3 and side(5,3,s=2) == 2
assert side(5,3,p=1,s=2) == 3 and side(5,3,p=1) == 5
image = [[1,2,0],[0,3,1],[2,1,4]]
kernel = [[1,0],[1,0]]
result = [[sum(image[y+dy][x+dx]*kernel[dy][dx] for dy in range(2) for dx in range(2)) for x in range(2)] for y in range(2)]
assert result == [[1,5],[2,4]]
assert 2*3*3*3+2 == 56 and 2*3*3*3 == 54
assert 3*32*32 == 3072 and 2*14*14 == 392
assert side(side(8,3),3)//2 == 2 and 2*2*2 == 8
pool = [[1,4,2,0],[3,2,5,1],[0,2,7,3],[1,6,2,4]]
pooled = [[max(pool[y+dy][x+dx] for dy in range(2) for dx in range(2)) for x in (0,2)] for y in (0,2)]
assert pooled == [[4,5],[6,7]]
assert sum((1,4,3,2))/4 == 2.5
assert (5-2)//2+1 == 2 and (7-2)//2+1 == 3
assert [max(x[i:i+2]) for x in [[1,4,0,0]] for i in (0,2)] == [4,0]
assert [max(x[i:i+2]) for x in [[0,1,4,0]] for i in (0,2)] == [1,4]
assert -2 + 8 == 6
assert [(x+1)/2 for x in (-1,0,1)] == [0,0.5,1]



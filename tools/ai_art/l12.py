from math import sqrt
for t in range(1,6):
    for axis,scale in ((0,8),(1,2)):
        gradients = [scale*p[axis] for p in PATHS["Adam"][:t]]
        mean = sum((1-0.9)*0.9**(t-1-j)*g for j,g in enumerate(gradients))/(1-0.9**t)
        square = sum((1-0.999)*0.999**(t-1-j)*g*g for j,g in enumerate(gradients))/(1-0.999**t)
